#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const reportPath = path.join(root, "packages/hermes-dashboard-kit/adoption/reports/latest-adoption-report.json");
const docsJsonPath = path.join(root, "docs/design/project-dashboard-tier-assessment.json");
const backlogJsonPath = path.join(root, "docs/design/dashboard-cross-project-action-backlog.json");
const backlogMarkdownPath = path.join(root, "docs/design/dashboard-cross-project-action-backlog.md");
const webDataPath = path.join(root, "web/src/pages/project-tier-assessment-data.ts");

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function projectAssessment(result) {
  const experienceTier = result.experienceTier ?? {};
  return {
    project: result.project,
    name: result.name,
    auditStatus: result.status,
    coarseTier: {
      current: experienceTier.current,
      target: experienceTier.target
    },
    currentBand: experienceTier.currentBand ?? "T0L",
    currentBandLabel: experienceTier.currentBandLabel ?? "",
    targetBand: experienceTier.targetBand ?? "",
    targetBandLabel: experienceTier.targetBandLabel ?? "",
    implementationMode: experienceTier.implementationMode ?? "",
    warnings: (result.issues ?? []).filter((issue) => issue.severity === "warning").map((issue) => issue.code),
    errors: (result.issues ?? []).filter((issue) => issue.severity === "error").map((issue) => issue.code),
    nextMove: experienceTier.nextAction ?? "",
    externalWorkItems: result.externalWorkItems ?? []
  };
}

function tsString(value) {
  return JSON.stringify(value, null, 2);
}

if (!fs.existsSync(reportPath)) {
  console.error(`Missing adoption report: ${path.relative(root, reportPath)}`);
  console.error("Run: npm run dashboard-kit:adoption:report");
  process.exit(1);
}

const report = readJson(reportPath);
const assessment = {
  schemaVersion: 1,
  generatedAt: report.generatedAt,
  sourceCommand: "npm run dashboard-kit:adoption:report",
  sourceHash: report.sourceHash,
  tierBands: report.experienceTierBands ?? [],
  projects: (report.results ?? []).map(projectAssessment)
};
const backlogItems = assessment.projects.flatMap((project) =>
  project.externalWorkItems.map((item) => ({
    project: project.project,
    projectName: project.name,
    currentBand: project.currentBand,
    targetBand: project.targetBand,
    auditStatus: project.auditStatus,
    ...item
  }))
);
const backlog = {
  schemaVersion: 1,
  generatedAt: assessment.generatedAt,
  sourceReport: "packages/hermes-dashboard-kit/adoption/reports/latest-adoption-report.json",
  items: backlogItems
};

function backlogMarkdown(data) {
  const rows = data.items.map((item) => (
    `| ${item.projectName} | ${item.priority} | \`${item.currentBand}\` | \`${item.targetBand || "unset"}\` | ${item.action} | ${item.reason} |`
  ));
  const backlogSection = rows.length
    ? `| Project | Priority | Current band | Target | Action | Reason |
|---|---:|---|---|---|---|
${rows.join("\n")}`
    : "No blocking cross-project dashboard action items are open in the latest adoption report.";
  return `# Dashboard Cross-Project Action Backlog

Date: ${data.generatedAt}
Source: \`${data.sourceReport}\`
Purpose: track required work that cannot be completed inside Nous Hermes Agent because it belongs in another project repository.

## Backlog

${backlogSection}

## Done Inside Nous Hermes Agent

- Refined tier bands are defined in the central dashboard-kit adoption registry.
- Adoption audit computes \`currentBand\`, \`targetBand\`, \`implementationMode\`, \`nextAction\`, and \`externalWorkItems\`.
- Latest adoption report is refreshed with computed tier-band fields.
- Design Intelligence UI reads generated project tier data from the latest report.
- Project tier assessment and external backlog artifacts are generated from the adoption report.

## Current Interpretation

- Empty backlog means no current adoption-blocking work is assigned to owning project repositories.
- Follow-up polish or expansion work should live in the roadmap, not in this blocking action backlog.
- No project should be promoted to a higher band unless the central audit evidence supports it.
`;
}

fs.writeFileSync(docsJsonPath, `${JSON.stringify(assessment, null, 2)}\n`);
fs.writeFileSync(backlogJsonPath, `${JSON.stringify(backlog, null, 2)}\n`);
fs.writeFileSync(backlogMarkdownPath, backlogMarkdown(backlog));
fs.writeFileSync(webDataPath, `// Generated by scripts/sync-dashboard-tier-assessment.mjs from latest-adoption-report.json.\n// Do not edit project tier rows manually; rerun npm run dashboard:tier-assessment:sync.\n\nexport interface ProjectTierExternalWorkItem {\n  ownerProject: string;\n  scope: string;\n  priority: string;\n  action: string;\n  reason: string;\n}\n\nexport interface ProjectTierAssessment {\n  project: string;\n  name: string;\n  auditStatus: \"current\" | \"needs-review\" | \"stale\" | \"missing\" | \"unregistered\" | \"invalid\";\n  coarseTier: { current: number | null; target: number | null };\n  currentBand: string;\n  currentBandLabel: string;\n  targetBand: string;\n  targetBandLabel: string;\n  implementationMode: string;\n  warnings: string[];\n  errors: string[];\n  nextMove: string;\n  externalWorkItems: ProjectTierExternalWorkItem[];\n}\n\nexport interface TierBand {\n  band: string;\n  tier: 0 | 1 | 2 | 3;\n  label: string;\n  meaning: string;\n}\n\nexport const projectTierGeneratedAt = ${JSON.stringify(assessment.generatedAt)};\nexport const projectTierSourceHash = ${JSON.stringify(assessment.sourceHash)};\n\nexport const tierBands: TierBand[] = ${tsString(assessment.tierBands)};\n\nexport const projectTierAssessments: ProjectTierAssessment[] = ${tsString(assessment.projects)};\n`);

console.log(`Wrote ${path.relative(root, docsJsonPath)}`);
console.log(`Wrote ${path.relative(root, backlogJsonPath)}`);
console.log(`Wrote ${path.relative(root, backlogMarkdownPath)}`);
console.log(`Wrote ${path.relative(root, webDataPath)}`);
