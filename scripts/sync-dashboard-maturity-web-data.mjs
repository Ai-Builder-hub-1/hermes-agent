#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const outputPath = path.join(root, "web/src/pages/dashboard-maturity-data.ts");
const sources = {
  promotionReadiness: "docs/design/dashboard-promotion-readiness.json",
  visualCoverage: "docs/design/dashboard-visual-coverage-report.json",
  visualEvidenceTasks: "docs/design/dashboard-visual-evidence-tasks.json",
  tokenDebtBacklog: "docs/design/dashboard-token-debt-backlog.json",
  componentEvidenceBacklog: "docs/design/dashboard-component-evidence-backlog.json",
  componentCertification: "docs/design/dashboard-component-certification-checklist.json"
};
const data = Object.fromEntries(Object.entries(sources).map(([key, file]) => [key, JSON.parse(fs.readFileSync(path.join(root, file), "utf8"))]));
const ts = `// Generated by scripts/sync-dashboard-maturity-web-data.mjs.
export const dashboardMaturityGeneratedAt = ${JSON.stringify(new Date().toISOString())};
export const promotionReadiness = ${JSON.stringify(data.promotionReadiness, null, 2)} as const;
export const visualCoverage = ${JSON.stringify(data.visualCoverage, null, 2)} as const;
export const visualEvidenceTasks = ${JSON.stringify(data.visualEvidenceTasks, null, 2)} as const;
export const tokenDebtBacklog = ${JSON.stringify(data.tokenDebtBacklog, null, 2)} as const;
export const componentEvidenceBacklog = ${JSON.stringify(data.componentEvidenceBacklog, null, 2)} as const;
export const componentCertification = ${JSON.stringify(data.componentCertification, null, 2)} as const;
`;
fs.writeFileSync(outputPath, ts);
console.log("Dashboard maturity web data synced.");
