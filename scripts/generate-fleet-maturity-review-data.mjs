#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const ledgerPath = path.join(root, "docs/fleet/fleet-evidence-ledger.json");
const suggestionsPath = path.join(root, "docs/fleet/fleet-maturity-suggestions.json");
const registryPath = path.join(root, "docs/fleet/fleet-registry.json");
const outputPath = path.join(root, "web/src/pages/fleet-maturity-review-data.ts");

function readJson(file, fallback) {
  if (!fs.existsSync(file)) return fallback;
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

const ledger = readJson(ledgerPath, { summary: {}, evidenceKinds: [], entries: [] });
const suggestions = readJson(suggestionsPath, { suggestions: [] });
const registry = readJson(registryPath, { projects: [] });
const projectById = new Map((registry.projects ?? []).map((project) => [project.id, project]));

const entries = (ledger.entries ?? []).map((entry) => {
  const project = projectById.get(entry.projectId) ?? {};
  return {
    id: entry.id,
    projectId: entry.projectId,
    projectName: project.name ?? entry.projectId,
    ownerSystem: project.ownerSystem ?? null,
    maturityRole: project.maturityRole ?? null,
    productionUrl: project.production?.url ?? null,
    proofUrl: project.production?.proofUrl ?? null,
    snapshotUrl: project.production?.snapshotUrl ?? null,
    kind: entry.kind,
    status: entry.status,
    severity: entry.severity,
    source: entry.source ?? null,
    lastCheckedAt: entry.lastCheckedAt ?? null,
    recommendedFix: entry.recommendedFix ?? null,
    findings: entry.findings ?? [],
    evidence: entry.evidence ?? null,
    promotion: entry.promotion ?? null,
    proof: entry.proof ?? null,
  };
});

const suggestionByWorkId = new Map((suggestions.suggestions ?? []).map((suggestion) => [suggestion.workItemId, suggestion]));
const enrichedEntries = entries.map((entry) => ({
  ...entry,
  suggestion: suggestionByWorkId.get(`${entry.projectId}.${entry.kind}.maturity`) ?? null,
}));

const reviewData = {
  schemaVersion: 1,
  generatedAt: ledger.generatedAt ?? new Date().toISOString(),
  purpose: "Fleet maturity review UI data generated from docs/fleet evidence ledgers.",
  summary: ledger.summary ?? {},
  evidenceKinds: ledger.evidenceKinds ?? [],
  entries: enrichedEntries,
};

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, `// Generated by scripts/generate-fleet-maturity-review-data.mjs. Do not edit by hand.\nexport const fleetMaturityReviewData = ${JSON.stringify(reviewData, null, 2)} as const;\n`);
console.log(`Wrote ${path.relative(root, outputPath)}`);
